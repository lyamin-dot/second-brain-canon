import sys,re
src,dst=sys.argv[1],sys.argv[2]
t=open(src,encoding='utf-8').read()
def rep(old,new,count=1):
    global t
    n=t.count(old)
    assert n==count,(old,n)
    t=t.replace(old,new)
H='\n\n'
rep('Область применения Применяется','## Область применения'+H+'Применяется')
rep('\nРоли Руководитель — проектирует.','\n## Роли'+H+'Руководитель — проектирует.')
rep('\nФормат наряда Печатается ВСЕГДА','\n## Формат наряда'+H+'Печатается ВСЕГДА')
# template
line=[l for l in t.split('\n') if l.startswith('<ID> НАРЯД ЗАДАЧА:')]
assert len(line)==1
L=line[0]
fields=[' ЗАДАЧА:',' DoD: (проверяемо',' РАМКА:',' МАНДАТ НА ОТКАЗ:',' ТРЕБУЕТ:',' ПАСПОРТ:',' ЗАМЫСЕЛ:',' ИСПОЛНИТЕЛЬ:',' МОДЕЛЬ:',' ГДЕ: чат проекта',' ОСНОВАНИЕ ГДЕ:',' РЕЗУЛЬТАТ В:']
N=L
for f in fields:
    assert N.count(f)==1,(f,N.count(f))
    N=N.replace(f,'\n'+f[1:])
assert N.count(' DoD в терминах объекта:')==1
N=N.replace(' DoD в терминах объекта:','\n```\n\nDoD в терминах объекта:')
t=t.replace(L,'```\n'+N)
rep('\n3.1 Выбор поля ГДЕ Умолчания нет.','\n## 3.1 Выбор поля ГДЕ'+H+'Умолчания нет.')
rep('\nНужен git push — доставка','\n1. Нужен git push — доставка')
rep('\nНужен git на чтение — клон','\n2. Нужен git на чтение — клон')
rep('\nНужен ли контекст Claude-Project','\n3. Нужен ли контекст Claude-Project')
rep('\nИсполнитель создаёт новый артефакт','\n4. Исполнитель создаёт новый артефакт')
rep(' 3.1а Выбор поля МОДЕЛЬ. Введён',H+'## 3.1а Выбор поля МОДЕЛЬ.'+H+'Введён')
rep('\nРаботе нужен весь каталог','\n1. Работе нужен весь каталог')
rep('ДА → высший. Наряд проверяет суждение','ДА → высший.\n2. Наряд проверяет суждение')
rep('\nУ шага написана процедура, гипотеза готова','\n3. У шага написана процедура, гипотеза готова')
rep('ДА → средний. Ни одно не сработало',' ДА → средний.'.lstrip()+H+'Ни одно не сработало')
rep('\n3.3 Маркировка ID = Н-ДД.ММ-NN','\n## 3.3 Маркировка ID = Н-ДД.ММ-NN')
rep('.2, .3 Больше одной точки','.2, .3'+H+'Больше одной точки')
rep('Префикс проекта не вводится. ID — первое слово','Префикс проекта не вводится.'+H+'ID — первое слово')
rep('во всех направлениях:\n\nвыдача: Н-08.08-02 НАРЯД','во всех направлениях:\n\n- выдача: Н-08.08-02 НАРЯД')
for a in [' отказ приёма: Н-08',' приём: Н-08',' закрытие: Н-08',' сводка Прораба: Н-08',' отмена Андреем: Н-08']:
    rep(a,'\n- '+a[1:])
rep('ОТМЕНЁН. Сообщение о наряде без ID','ОТМЕНЁН.'+H+'Сообщение о наряде без ID')
rep('\n3.4 Мандат на отказ РАМКА говорит','\n## 3.4 Мандат на отказ'+H+'РАМКА говорит')
rep('\nпроцедура — вправе объявить','\n- процедура — вправе объявить')
for a in [' посылка — вправе',' цифры — вправе',' вход — вправе',' нет — отказ не предусмотрен']:
    rep(a,'\n- '+a[1:])
rep('выполнять как написано Для нарядов на проверку','выполнять как написано'+H+'Для нарядов на проверку')
rep('<на каком основании>. Это закрытие наряда','<на каком основании>.'+H+'Это закрытие наряда')
rep('\nОграничители Глубина 1.','\n## Ограничители'+H+'Глубина 1.')
for a in [' Потолок 5. Больше пяти',' Нет DoD — нет наряда.',' Один файл — один наряд, в обе стороны.',' Конкуренция: два наряда',' Охват: один наряд',' Конкуренция касается и Руководителя',' Потолок правок и обязательный паспорт']:
    rep(a,H+a[1:])
rep(' Приёмка Приёмка только по объекту',H+'## Приёмка'+H+'Приёмка только по объекту')
for a in [' Приёмка правки построчного списка',' Отдельный наряд на приёмку оправдан']:
    rep(a,H+a[1:])
rep('\nЧего этот Skill НЕ определяет Роли распределяют','\n## Чего этот Skill НЕ определяет'+H+'Роли распределяют')
rep('\nГраницы Не заменяет context-handoff','\n## Границы'+H+'Не заменяет context-handoff')
rep('\nНАРЯД — распределение ролей внутри Claude-Project\n','\n# НАРЯД — распределение ролей внутри Claude-Project\n')
open(dst,'w',encoding='utf-8').write(t)
